#!/usr/bin/env python3
"""Gera o README.md de cada tópico a partir de topic.json e index.json.

Só sobrescreve READMEs que contêm o marcador GENERATED (ou que ainda não existem),
para não apagar READMEs escritos à mão.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GENERATED = "<!-- generated by tools/build_readmes.py -->"


def build_readme(topic_dir):
    topic = json.loads((topic_dir / "topic.json").read_text(encoding="utf-8"))
    index = json.loads((topic_dir / "index.json").read_text(encoding="utf-8"))
    lessons = index["lessons"]

    lines = [GENERATED, f"# {topic['mainTopic']} ({topic['language']})", "", topic["description"], ""]
    source_format = topic.get("sourceFormat", "markdown")
    quizzes = sum(l["quizCount"] for l in lessons)
    if topic.get("durationMinutes"):
        lines.append(f"- {len(lessons)} lições · aulas de {topic['durationMinutes']} minutos ({topic['format']})")
    else:
        lines.append(f"- {len(lessons)} lições")
    if topic.get("lessonPlan"):
        lines.append(f"- Estrutura: {topic['lessonPlan']}")
    if topic.get("level"):
        lines.append(f"- Nível: {topic['level']}")
    if topic.get("levels"):
        lines.append(f"- Níveis: {topic['levels']}")
    if topic.get("spelling"):
        lines.append(f"- Grafia: {topic['spelling']}")
    if source_format == "markdown":
        lines.append("- 3 quizzes interativos por lição (`vocab`, `practice`, `homework`) no formato do nó Tiptap `quiz`")
        lines += ["", "Arquivos: `source/` (Markdown editável) → `lessons/` (JSON gerado). Índice completo em `index.json`.", ""]
    else:
        if quizzes:
            lines.append(f"- {quizzes} quizzes interativos no formato do nó Tiptap `quiz`")
        lines += ["", topic["structureNote"], ""]
        origin = "HTML" if source_format == "html" else "JSON"
        lines += [f"Arquivos: `source/` ({origin} original) → `lessons/` (JSON Tiptap gerado por `tools/build_workbooks.py`). "
                  "Índice completo em `index.json`." + (" Plano de aula do professor em `guidelines.md`." if topic.get("guidelines") else ""), ""]

    for course in topic["courses"]:
        course_lessons = [l for l in lessons if l["id"].startswith(course["code"] + "-")]
        if len(topic["courses"]) > 1:
            lines += [f"## {course['name']}", ""]
        unit = None
        for lesson in course_lessons:
            if lesson["unit"] != unit:
                if unit is not None:
                    lines.append("")
                unit = lesson["unit"]
                lines += [f"### {unit}", "", "| # | Lição | Nível | Quizzes / perguntas |", "|---|---|---|---|"]
            lines.append(
                f"| {lesson['lessonNumber']:02d} | [{lesson['title']}]({lesson['file']}) | {lesson['level']} "
                f"| {lesson['quizCount']} / {lesson['questionCount']} |"
            )
        lines.append("")

    if topic.get("officialReferences"):
        lines += ["## Referências", ""] + [f"- {url}" for url in topic["officialReferences"]] + [""]
    return "\n".join(lines)


def main():
    for topic_file in sorted(ROOT.glob("*/*/topic.json")):
        topic_dir = topic_file.parent
        readme = topic_dir / "README.md"
        if readme.exists() and GENERATED not in readme.read_text(encoding="utf-8"):
            print(f"{topic_dir.relative_to(ROOT)}: README manual mantido")
            continue
        readme.write_text(build_readme(topic_dir), encoding="utf-8")
        print(f"{topic_dir.relative_to(ROOT)}: README gerado")


if __name__ == "__main__":
    main()
